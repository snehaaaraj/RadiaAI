"""A minimal, dependency-free JSON Schema validator for MCP tool arguments.

Deliberately not the ``jsonschema`` package: it pulls in ``rpds-py``, a
Rust-compiled binary wheel, as a transitive dependency. A binary wheel that
installs cleanly on a developer's machine is exactly the kind of dependency
that can silently fail to resolve on a different serverless platform/
architecture (no matching prebuilt wheel, no compiler available to build from
source) - this module avoids that entire risk class by implementing only the
small, well-defined subset of JSON Schema that mcp-radia's own tool schemas
actually use (generated by the MCP SDK from Pydantic ``Annotated`` function
signatures): ``type``, ``properties``, ``required``, ``enum``, ``anyOf``,
``minimum``/``maximum``/``exclusiveMinimum``/``exclusiveMaximum``, and
``minLength``/``maxLength``. Anything outside that - a schema keyword this
module does not recognize - is simply not checked, which is a deliberately
conservative failure mode for a validator whose job is to catch obviously bad
arguments before they reach mcp-radia, not to be a general-purpose validator.
"""

from __future__ import annotations

from typing import Any

#: JSON Schema "type" keyword values mapped to the Python types ``isinstance``
#: should accept. Booleans are checked before integers (``bool`` is a
#: subclass of ``int`` in Python) so a JSON Schema "integer" never silently
#: accepts ``True``/``False``.
_TYPE_CHECKS: dict[str, tuple[type, ...]] = {
    "string": (str,),
    "boolean": (bool,),
    "integer": (int,),
    "number": (int, float),
    "array": (list,),
    "object": (dict,),
    "null": (type(None),),
}


class SchemaValidationError(ValueError):
    """Raised when a value fails to satisfy a JSON Schema fragment.

    Carries a ``.message`` attribute (rather than relying on ``str(exc)``)
    for parity with ``jsonschema.exceptions.ValidationError``, the package
    this module replaces.
    """

    def __init__(self, message: str) -> None:
        super().__init__(message)
        self.message = message


def _check_type(value: object, type_name: str, path: str) -> None:
    if type_name == "boolean":
        if not isinstance(value, bool):
            raise SchemaValidationError(f"{path}: expected boolean, got {type(value).__name__}")
        return
    if type_name == "integer" and isinstance(value, bool):
        raise SchemaValidationError(f"{path}: expected integer, got boolean")
    expected = _TYPE_CHECKS.get(type_name)
    if expected is None:
        return  # Unrecognized type keyword: conservative no-op, see module docstring.
    if not isinstance(value, expected):
        raise SchemaValidationError(f"{path}: expected {type_name}, got {type(value).__name__}")


def _validate_node(value: object, schema: dict[str, Any], path: str) -> None:
    if "anyOf" in schema:
        errors: list[str] = []
        for subschema in schema["anyOf"]:
            try:
                _validate_node(value, subschema, path)
                return  # One branch matched - anyOf is satisfied.
            except SchemaValidationError as exc:
                errors.append(exc.message)
        raise SchemaValidationError(
            f"{path}: did not match any allowed schema ({'; '.join(errors)})"
        )

    type_name = schema.get("type")
    if isinstance(type_name, str):
        _check_type(value, type_name, path)

    if "enum" in schema and value not in schema["enum"]:
        raise SchemaValidationError(f"{path}: {value!r} is not one of {schema['enum']!r}")

    if isinstance(value, int | float) and not isinstance(value, bool):
        if "minimum" in schema and value < schema["minimum"]:
            raise SchemaValidationError(
                f"{path}: {value} is less than the minimum {schema['minimum']}"
            )
        if "maximum" in schema and value > schema["maximum"]:
            raise SchemaValidationError(
                f"{path}: {value} is greater than the maximum {schema['maximum']}"
            )
        if "exclusiveMinimum" in schema and value <= schema["exclusiveMinimum"]:
            raise SchemaValidationError(
                f"{path}: {value} must be greater than {schema['exclusiveMinimum']}"
            )
        if "exclusiveMaximum" in schema and value >= schema["exclusiveMaximum"]:
            raise SchemaValidationError(
                f"{path}: {value} must be less than {schema['exclusiveMaximum']}"
            )

    if isinstance(value, str):
        if "minLength" in schema and len(value) < schema["minLength"]:
            raise SchemaValidationError(f"{path}: shorter than minLength {schema['minLength']}")
        if "maxLength" in schema and len(value) > schema["maxLength"]:
            raise SchemaValidationError(f"{path}: longer than maxLength {schema['maxLength']}")

    if isinstance(value, dict) and "properties" in schema:
        properties = schema["properties"]
        for required_key in schema.get("required", []):
            if required_key not in value:
                raise SchemaValidationError(f"{path}: missing required property '{required_key}'")
        for key, item in value.items():
            subschema = properties.get(key)
            if subschema is not None:
                _validate_node(item, subschema, f"{path}.{key}" if path else key)


def validate(instance: dict[str, object], schema: dict[str, Any]) -> None:
    """Validate ``instance`` against ``schema``, raising :class:`SchemaValidationError` on failure.

    Mirrors ``jsonschema.Draft202012Validator(schema).validate(instance)``'s
    contract for the subset of the spec this module supports: returns
    normally when valid, raises with a ``.message`` describing the first
    failure found when not.

    A malformed ``schema`` (e.g. ``required`` not a list) raises
    :class:`SchemaValidationError` too, rather than a raw ``TypeError``/
    ``KeyError`` - the caller's job is "reject this call safely", and a
    broken schema from mcp-radia is exactly as much reason to reject as a
    broken argument is.
    """
    try:
        _validate_node(instance, schema, path="")
    except SchemaValidationError:
        raise
    except (TypeError, KeyError, AttributeError) as exc:
        raise SchemaValidationError(f"schema is malformed: {exc}") from exc
